export const getShopCharacters = (): ShopItem[] => {
  return CHARACTERS_ROSTER.map((char) => ({
    id: `char_${char.id}`,
    type: 'character',
    name: char.name,
    description: `${char.title} · ${char.bio}`,
    cost: char.cost ?? (char.rarity === 'legendary' ? 800 : char.rarity === 'epic' ? 500 : char.rarity === 'rare' ? 250 : 0),
    rarity: char.rarity ?? 'common',
    icon: '💃',
    characterId: char.id,
  }));
};
